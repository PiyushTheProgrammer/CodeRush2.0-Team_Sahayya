@router.post("/start", response_model=ResearchStartResponse, status_code=status.HTTP_202_ACCEPTED)
async def start_research_task(
    request: ResearchStartRequest,
    background_tasks: BackgroundTasks,
    db: Optional[AsyncSession] = Depends(get_db),
):
    """
    Initiate LangGraph research pipeline as a background task. Returns task_id.
    """
    task_id_uuid = uuid.uuid4()
    task_id_str = str(task_id_uuid)

    IN_MEMORY_TASKS[task_id_str] = {
        "task_id": task_id_str,
        "user_prompt": request.user_prompt,
        "status": "IN_PROGRESS",
        "current_step": "LANGGRAPH_DAG_INIT",
        "passages": [],
        "claims": [],
        "report_md": "",
        "logs": [
            {
                "id": str(uuid.uuid4()),
                "action": "RESEARCH_TASK_STARTED",
                "target": "Research API Router",
                "status": "IN_PROGRESS",
                "timestamp": "Just now",
                "details": {"prompt": request.user_prompt, "self_evolve": request.self_evolve},
            }
        ],
    }

    if db is not None:
        try:
            new_task = ResearchTask(id=task_id_uuid, user_prompt=request.user_prompt, status="IN_PROGRESS")
            db.add(new_task)
            initial_log = AuditLog(
                id=uuid.uuid4(),
                task_id=task_id_uuid,
                action="RESEARCH_TASK_STARTED",
                target="Research API Router",
                status="IN_PROGRESS",
                details={"prompt": request.user_prompt},
            )
            db.add(initial_log)
            await db.commit()
        except Exception as db_err:
            logger.warning(f"Database insertion warning in /start endpoint: {db_err}")
            try:
                await db.rollback()
            except Exception:
                pass

    background_tasks.add_task(_execute_research_background, task_id_str, request.user_prompt, request.top_k)

    return ResearchStartResponse(
        task_id=task_id_str,
        status="IN_PROGRESS",
        message="LangGraph research pipeline started as background task.",
    )


@router.get("/{task_id}/status", response_model=TaskStatusResponse)
async def get_research_task_status(task_id: str, db: Optional[AsyncSession] = Depends(get_db)):
    """
    Return current step, status, and live log updates (from DB AuditLog or in-memory state).
    """
    try:
        task_id_uuid = uuid.UUID(task_id)
    except ValueError:
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="Invalid task_id format.")

    logs_list: List[AuditLogDetail] = []
    task_status = "UNKNOWN"
    current_step = "INITIALIZING"

    # Query DB if available
    if db is not None:
        try:
            res_task = await db.execute(select(ResearchTask).where(ResearchTask.id == task_id_uuid))
            db_task = res_task.scalar_one_or_none()
            if db_task:
                task_status = db_task.status
                res_logs = await db.execute(
                    select(AuditLog).where(AuditLog.task_id == task_id_uuid).order_by(AuditLog.timestamp.asc())
                )
                db_logs = res_logs.scalars().all()
                if db_logs:
                    current_step = db_logs[-1].action
                    logs_list = [
                        AuditLogDetail(
                            id=str(log.id),
                            action=log.action,
                            target=log.target,
                            status=log.status,
                            timestamp=log.timestamp.strftime("%H:%M:%S") if log.timestamp else "Recently",
                            details=log.details,
                        )
                        for log in db_logs
                    ]
        except Exception as e:
            logger.warning(f"Database query warning in status endpoint: {e}")

    # Fallback to in-memory store if DB had no records
    if not logs_list and task_id in IN_MEMORY_TASKS:
        mem_data = IN_MEMORY_TASKS[task_id]
        task_status = mem_data["status"]
        current_step = mem_data["current_step"]
        logs_list = [
            AuditLogDetail(
                id=l["id"],
                action=l["action"],
                target=l["target"],
                status=l["status"],
                timestamp=l["timestamp"],
                details=l.get("details"),
            )
            for l in mem_data.get("logs", [])
        ]

    if not logs_list and task_status == "UNKNOWN":
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Research task not found.")

    return TaskStatusResponse(
        task_id=task_id,
        status=task_status,
        current_step=current_step,
        logs=logs_list,
    )


